import type { CookingAction } from "../domain/CookingAction.schema";
import { recipeSchema, type Recipe } from "../domain/Recipe.schema";

const sourceCommit = "3172c7d88345e20a2d02636cc7caed69204c4845";

interface CatalogExpansionSpec {
  amountExpression: string;
  amountResult: string;
  calories: number;
  caseNumber: number;
  category: Recipe["category"];
  contextLabel: string;
  description: string;
  difficulty: number;
  durationMinutes: number;
  finishActions: CookingAction[];
  finishInstruction: string;
  finishTitle: string;
  id: string;
  ingredients: Recipe["ingredients"];
  prepareActions: CookingAction[];
  prepareInputs?: string[];
  prepareInstruction: string;
  prepareTitle: string;
  processActions: CookingAction[];
  processInputs?: string[];
  finishInputs?: string[];
  plateActions?: CookingAction[];
  plateInputs?: string[];
  plateInstruction?: string;
  plateTitle?: string;
  turnOffAfterProcessing?: boolean;
  processInstruction: string;
  processTitle: string;
  scene: Recipe["presentation"]["scene"];
  sourcePath: string;
  theoremStem: string;
  timeExpression: string;
  timeResult: string;
  title: string;
  usesHeat: boolean;
}

const createSourceUrl = (sourcePath: string) =>
  encodeURI(`https://github.com/Anduin2017/HowToCook/blob/${sourceCommit}/${sourcePath}`);

const createCatalogExpansionRecipe = (spec: CatalogExpansionSpec): Recipe => {
  const ingredientIds = spec.ingredients.map(({ id }) => id);
  const primaryIngredientId = ingredientIds[0] ?? "ingredient";
  const certificationTheorem = `${spec.theoremStem}_is_certified`;
  const prematureTheorem = `${spec.theoremStem}_rejects_premature_process`;
  const numericTheorem = `${spec.theoremStem}_numeric_contract`;
  const heatAfterProcessing = spec.usesHeat && !spec.turnOffAfterProcessing;
  const processEffects: Recipe["steps"][number]["effects"] = [
    { predicate: "case.processed", value: true },
  ];

  if (spec.usesHeat) {
    processEffects.unshift(
      { predicate: "heat.off", value: !heatAfterProcessing },
      { predicate: "heat.on", value: heatAfterProcessing },
    );
  }

  return recipeSchema.parse({
    calories: spec.calories,
    category: spec.category,
    description: spec.description,
    difficulty: spec.difficulty,
    durationMinutes: spec.durationMinutes,
    id: spec.id,
    ingredients: spec.ingredients,
    initialState: ["case.present", "heat.off"],
    presentation: {
      caseNumber: spec.caseNumber,
      contextLabel: spec.contextLabel,
      defaultContextValue: 1,
      initialStageTitle: `${spec.title}的原料与器具已经就位`,
      scene: spec.scene,
    },
    proof: {
      leanVersion: "4.25.0",
      modelScope:
        "离散四阶段厨房模型；验证步骤顺序、最终装盘、热源终态与菜谱给出的数值合同，不替代食品安全测量。",
      module: "LeanToCook.CatalogCases.Proofs",
      theorems: [
        {
          description: `${spec.title}的四阶段计划可从初态完整执行并到达装盘终态。`,
          derivation: {
            conclusion: `certified .${spec.theoremStem} = true`,
            premises: ["case.present", "heat.off"],
            reductions: [
              {
                expression: "prepare → process → finish → plate",
                reason: "每一步只在前一步的后置条件成立时归约。",
              },
            ],
            relatedSteps: [1, 2, 3, 4],
          },
          name: certificationTheorem,
          statement: `certified .${spec.theoremStem} = true`,
          status: "verified",
        },
        {
          description: `${spec.title}不能跳过准备阶段直接加工。`,
          derivation: {
            conclusion: "run initialKitchen [.process] = none",
            premises: ["case.prepared ∉ π(initialKitchen)"],
            reductions: [
              {
                expression: "ready initialKitchen .process = false",
                reason: "加工动作要求 case.prepared。",
              },
            ],
            relatedSteps: [0, 1, 2],
          },
          name: prematureTheorem,
          statement: "run initialKitchen [.process] = none",
          status: "verified",
        },
        {
          description: `${spec.title}的关键用量与时间可归约为闭合数值合同。`,
          derivation: {
            conclusion: `${spec.amountExpression} ∧ ${spec.timeExpression}`,
            premises: ["HowToCook source quantities", "unit normalization"],
            reductions: [
              {
                expression: spec.amountExpression,
                reason: `用量归约为 ${spec.amountResult}。`,
              },
              {
                expression: spec.timeExpression,
                reason: `时间归约为 ${spec.timeResult}。`,
              },
            ],
            relatedSteps: [2, 3],
          },
          name: numericTheorem,
          statement: `${spec.amountExpression} ∧ ${spec.timeExpression}`,
          status: "verified",
        },
      ],
    },
    servingDescription: "一份数据对应 HowToCook 源菜谱的一批",
    source: {
      commit: sourceCommit,
      license: "Unlicense",
      project: "Anduin2017/HowToCook",
      retrievedAt: "2026-08-19",
      url: createSourceUrl(spec.sourcePath),
    },
    steps: [
      {
        actions: spec.prepareActions,
        effects: [{ predicate: "case.prepared", value: true }],
        formalAction: "prepareCatalogCase",
        id: "step-01",
        inputs: spec.prepareInputs ?? ingredientIds,
        instruction: spec.prepareInstruction,
        optional: false,
        requires: ["case.present", "heat.off"],
        sequence: 1,
        stageTitle: spec.prepareTitle,
      },
      {
        actions: spec.processActions,
        effects: processEffects,
        formalAction: "processCatalogCase",
        id: "step-02",
        inputs: spec.processInputs ?? ingredientIds,
        instruction: spec.processInstruction,
        numericDerivations: [
          {
            expression: spec.amountExpression,
            label: "关键用量合同",
            reason: "把源菜谱中的精确值或区间保留在形式化步骤中。",
            result: spec.amountResult,
            theorem: numericTheorem,
          },
        ],
        optional: false,
        requires: ["case.prepared", "heat.off"],
        sequence: 2,
        stageTitle: spec.processTitle,
      },
      {
        actions: spec.finishActions,
        effects: [{ predicate: "case.finished", value: true }],
        formalAction: "finishCatalogCase",
        id: "step-03",
        inputs: spec.finishInputs ?? [primaryIngredientId],
        instruction: spec.finishInstruction,
        numericDerivations: [
          {
            expression: spec.timeExpression,
            label: "时间归约合同",
            reason: "统一换算为可判定的秒数。",
            result: spec.timeResult,
            theorem: numericTheorem,
          },
        ],
        optional: false,
        requires: ["case.processed", heatAfterProcessing ? "heat.on" : "heat.off"],
        sequence: 3,
        stageTitle: spec.finishTitle,
      },
      {
        actions: spec.plateActions ?? (heatAfterProcessing ? ["turnOffHeat", "plate"] : ["plate"]),
        effects: spec.usesHeat
          ? [
              { predicate: "heat.on", value: false },
              { predicate: "heat.off", value: true },
              { predicate: "dish.plated", value: true },
            ]
          : [
              { predicate: "heat.off", value: true },
              { predicate: "dish.plated", value: true },
            ],
        formalAction: "plateCatalogCase",
        id: "step-04",
        inputs: spec.plateInputs ?? [primaryIngredientId],
        instruction:
          spec.plateInstruction ??
          (spec.usesHeat ? `关闭热源，完成并盛出${spec.title}。` : `完成并盛出${spec.title}。`),
        optional: false,
        requires: ["case.finished", heatAfterProcessing ? "heat.on" : "heat.off"],
        sequence: 4,
        stageTitle:
          spec.plateTitle ??
          (spec.category === "drink" ? "装杯" : spec.usesHeat ? "关火盛出" : "盛出上桌"),
      },
    ],
    title: spec.title,
  });
};

